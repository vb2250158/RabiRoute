test("DSBot rule view selects explicit assignments across unbound roles and isolates bad roles", async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "rabi-dsbot-rules-"));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const target = { kind: "ds_bot", agentAdapter: "dsh", agentTargetId: "owner-a", botScopeId: "scope-a", botId: "bot-a", botName: "Example" };
  const rule = (destination: unknown) => ({ id: "same-id", enabled: false, trigger: { type: "schedule", schedule: { type: "daily", timeOfDays: ["09:00", "17:00"] } }, action: { type: "deliver_agent", target: destination, message: "Editable action" } });
  const write = async (roleId: string, value: unknown) => { await fs.mkdir(path.join(root, roleId), { recursive: true }); await fs.writeFile(path.join(root, roleId, "personaConfig.json"), JSON.stringify(value)); };
  await write("RoleA", { automationRules: [rule(target)] });
  await write("RoleB", { automationRules: [rule({ ...target, agentTargetId: "owner-b" })] });
  await write("OtherScope", { automationRules: [rule({ ...target, botScopeId: "scope-b" })] });
  await write("PersonaMatchOnly", { automationRules: [rule({ kind: "recipient", recipientId: "primary" })] });
  await write("Archived", { automationRules: [rule(target)] });
  await fs.writeFile(path.join(root, "Archived", "roleMetadata.json"), JSON.stringify({ schemaVersion: 1, revision: 1, archivedAt: "2026-01-01T00:00:00Z" }));
  await write("Broken", null);
  let generation = "one";
  const owner = createDsBotAutomationRuleOwner({ rolesRoot: () => root, identity: () => ({ applicationGenerationId: generation, managerInstanceId: "fixture" }) });
  const registry = new ManagerPluginRouteRegistry();
  const registration = registry.registerOperations("dsbot-rule-fixture", [...createDsBotAutomationRuleOperations(owner), ...createRoleConfigurationOperations({ rolesRoot: () => root, identity: () => ({ applicationGenerationId: generation, managerInstanceId: "fixture" }), routes: () => [], assertCatalogReady() {}, async changed() { owner.invalidate(); } })]);
  const server = http.createServer((request, response) => { markAuthenticatedConnectionRequest(request); if (!registry.handle(request, new URL(request.url!, "http://fixture"), response)) response.writeHead(404).end(); });
  await new Promise<void>(resolve => server.listen(0, "127.0.0.1", resolve));
  t.after(async () => { server.closeAllConnections(); await registration.dispose(); await new Promise<void>(resolve => server.close(() => resolve())); });
  const base = `http://127.0.0.1:${(server.address() as { port: number }).port}/api/automation/ds-bot-rules?botScopeId=scope-a&botId=bot-a`;
  const get = async (suffix = "") => { const response = await fetch(base + suffix); return { status: response.status, body: await response.json() }; };
  const first = await get("&limit=1");
  assert.equal(first.status, 200); assert.equal(first.body.data.total, 2);
  assert.equal(first.body.data.items[0].sourceRoleId, "RoleA");
  assert.equal(first.body.data.items[0].rawRuleId, "same-id");
  assert.deepEqual(first.body.data.items[0].rule, rule(target));
  assert.ok(first.body.data.warnings.some((warning: { roleId: string; code: string }) => warning.roleId === "Broken" && warning.code === "ROLE_CONFIGURATION_UNAVAILABLE"));
  const second = await get("&cursor=" + first.body.data.nextCursor);
  assert.equal(second.body.data.items[0].sourceRoleId, "RoleB");
  assert.notEqual(first.body.data.items[0].id, second.body.data.items[0].id);
  assert.equal((await get("&agentTargetId=owner-b")).body.data.total, 1);
  assert.equal((await get("&agentTargetId=owner-b&cursor=" + first.body.data.nextCursor)).status, 409);
  const [one, two] = await Promise.all([owner.snapshot(), owner.snapshot()]);
  one.items.length = 0; assert.equal(two.items.length, 3);
  await write("RoleA", { automationRules: [] });
  assert.equal((await get()).body.data.total, 2);
  owner.invalidate(); assert.equal((await get()).body.data.total, 1);
  assert.equal((await get("&cursor=" + first.body.data.nextCursor)).status, 409);
  await write("RoleB", { automationRules: [] });
  generation = "two"; assert.equal((await get()).body.data.total, 0);
  await write("RoleB", { padding: "x".repeat(2 * 1024 * 1024 + 1), automationRules: [null, rule(target)] });
  owner.invalidate();
  const large = await get();
  assert.equal(large.body.data.total, 1);
  assert.ok(large.body.data.refreshedAt); assert.equal(large.body.data.maxCacheAgeMs, 30_000);
  assert.ok(large.body.data.warnings.some((warning: { code: string }) => warning.code === "AUTOMATION_RULE_INVALID"));
  const scheduled = { ...rule({ ...target, agentTargetId: "local:dsh", dshBaseUrl: "http://localhost:3000" }), enabled: true, trigger: { type: "schedule", schedule: { type: "daily_time", timeOfDays: ["09:00", "17:00"] } } };
  await write("RoleB", { automationRules: [scheduled, { ...scheduled, id: "route-only", sourceRouteIds: ["real-route"] }, { ...scheduled, id: "invalid", action: { type: "deliver_agent", target: { ...target, botId: "" } } }] });
  owner.invalidate();
  let changes = 0;
  const unsubscribe = owner.subscribeChanged(() => { changes++; });
  owner.invalidate(); assert.equal(changes, 1); unsubscribe();
  const schedules = await owner.readScheduleSnapshot();
  assert.equal(schedules.tasks.length, 1);
  assert.equal(schedules.tasks[0]!.sourceRoleId, "RoleB");
  assert.equal("route" in schedules.tasks[0]!, false);
  assert.ok(schedules.warnings.some(warning => warning.code === "ROLE_AUTOMATION_ROUTE_CONSTRAINT"));
  assert.ok(schedules.warnings.some(warning => warning.code === "AUTOMATION_SCHEDULE_INVALID"));
  const exact = await get("&dshBaseUrl=" + encodeURIComponent("http://localhost:3000"));
  assert.equal(exact.body.data.total, 2);
  assert.equal((await get("&dshBaseUrl=" + encodeURIComponent("http://localhost:3001"))).body.data.total, 0);
  assert.equal((await get("&instanceBinding=%7Bbad")).status, 400);
  const configurationUrl = `http://127.0.0.1:${(server.address() as { port: number }).port}/api/roles/RoleB/configuration`;
  const detail = await (await fetch(configurationUrl)).json();
  const saved = await fetch(configurationUrl, { method: "PUT", headers: { "content-type": "application/json", "idempotency-key": "source-save-fixture" }, body: JSON.stringify({ expectedRevision: detail.data.revision, config: { ...detail.data.config, automationRules: [scheduled] } }) });
  assert.equal(saved.status, 200);
  assert.equal((await get()).body.data.total, 1);
  await assert.rejects(owner.acquireTaskLease("Archived", schedules.tasks[0]!.storageOwner), /归档/);
  const lease = await owner.acquireTaskLease("RoleB", schedules.tasks[0]!.storageOwner);
  lease.assertCurrent(); generation = "three";
  assert.throws(lease.assertCurrent, /owner changed/);
  const reading = owner.snapshot();
  let disposed = false;
  const disposing = owner.dispose().then(() => { disposed = true; });
  await new Promise<void>(resolve => setImmediate(resolve)); assert.equal(disposed, false);
  await lease.release(); await disposing; await reading;
  await assert.rejects(owner.snapshot(), /disposed/);
});

test("existing catalog ready notification refreshes external role changes and unsubscribes", async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "rabi-role-source-watch-"));
  const directory = path.join(root, "Example");
  await fs.mkdir(directory);
  const file = path.join(directory, "personaConfig.json");
  await fs.writeFile(file, JSON.stringify({ automationRules: [] }));
  const owner = createDsBotAutomationRuleOwner({ rolesRoot: () => root, identity: () => ({ applicationGenerationId: "fixture", managerInstanceId: "fixture" }) });
  const lifecycle = new RouteCatalogStartupLifecycle({
    async apply() {},
    attemptFactory(_operation, identity) {
      const content = { routeRoot: path.join(root, "routes"), rolesRoot: root, gateways: [], personas: [] };
      return { result: Promise.resolve({ ...identity, ...content, ...routeCatalogSnapshotIdentities(content) }), async cancel() {} };
    }
  });
  t.after(async () => { await lifecycle.stop(); await owner.dispose(); await fs.rm(root, { recursive: true, force: true }); });
  await lifecycle.recapture();
  let changes = 0;
  const unsubscribe = lifecycle.onReady(() => { changes++; owner.invalidate(); });
  await new Promise<void>(resolve => setImmediate(resolve));
  assert.equal(changes, 1);
  assert.equal((await owner.snapshot()).items.length, 0);
  await fs.writeFile(file, JSON.stringify({ automationRules: [{ id: "external", trigger: { type: "schedule", schedule: { type: "interval", intervalSeconds: 60 } }, action: { type: "deliver_agent", message: "Task", target: { kind: "ds_bot", agentAdapter: "dsh", agentTargetId: "local:dsh", dshBaseUrl: "http://localhost:3000", botScopeId: "scope", botId: "bot", botName: "Bot" } } }] }));
  assert.equal((await owner.snapshot()).items.length, 0);
  await lifecycle.recapture();
  assert.equal(changes, 2);
  assert.equal((await owner.readScheduleSnapshot()).tasks.length, 1);
  unsubscribe(); await lifecycle.recapture(); assert.equal(changes, 2);
});
