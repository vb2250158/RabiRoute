import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
/** Compatibility metadata only; native activation remains the availability authority. */
export async function generateAgentPluginMetadata(root, { check = false } = {}) {
    const builtin = path.join(root, "src/plugins");
    const descriptors = [];
    const profile = JSON.parse(await fs.readFile(path.join(root, "plugins/profiles/desktop.json"), "utf8"));
    const selected = [...new Map(profile.instances.map(instance => [`${instance.package}@${instance.version}`, instance])).values()];
    for (const instance of selected) {
        const directory = encodeURIComponent(instance.package), version = instance.version;
        {
            const source = path.join(builtin, directory);
            let bytes;
            try {
                bytes = await fs.readFile(path.join(source, "agent-adapter.json"), "utf8");
            }
            catch (error) {
                if (error.code === "ENOENT")
                    continue;
                throw error;
            }
            const descriptor = JSON.parse(bytes);
            const manifest = JSON.parse(await fs.readFile(path.join(source, "rabi.plugin.json"), "utf8"));
            if (manifest.id !== directory || manifest.version !== version || descriptor.manifest?.type !== descriptor.type
                || !manifest.provides.includes(descriptor.capability))
                throw new Error(`Invalid Agent package metadata: ${directory}@${version}.`);
            if (descriptors.some(item => item.type === descriptor.type))
                throw new Error(`Duplicate Agent compatibility type: ${descriptor.type}.`);
            descriptors.push(descriptor);
        }
    }
    descriptors.sort((a, b) => a.type.localeCompare(b.type));
    const contents = `// Generated by scripts/generate-agent-plugin-metadata.mjs from package-owned descriptors.\n// Compatibility declarations do not imply that an adapter is enabled or active.\nexport const installedAgentAdapterManifests = ${JSON.stringify(descriptors.map(item => item.manifest), null, 2)} as const;\n`;
    const destination = path.join(root, "src/shared/agentAdapterManifests.generated.ts");
    if (check) {
        if (await fs.readFile(destination, "utf8") !== contents)
            throw new Error("Agent compatibility metadata is stale; run node scripts/generate-agent-plugin-metadata.mjs.");
    }
    else
        await fs.writeFile(destination, contents);
    return descriptors.length;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    console.log(`Agent metadata: ${await generateAgentPluginMetadata(process.cwd(), { check: process.argv.includes("--check") })} packages.`);
}
